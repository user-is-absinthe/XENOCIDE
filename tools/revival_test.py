"""Edge file://: одноразовое воскрешение, выплата поражения и сохранение расхода."""
from pathlib import Path
import json,os
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent.parent
ART=ROOT/'artifacts';ART.mkdir(exist_ok=True)
os.environ['TEMP']=os.environ['TMP']=str(ROOT/'.venv'/'tmp')
url=(ROOT/'dist'/'index.html').as_uri()
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1280,'height':720},offline=True)
    errors=[];network=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:network.append(r.url) if r.url.startswith(('http:','https:')) else None)
    page.goto(url)
    report=page.evaluate((ROOT/'tools'/'revival_checks.js').read_text(encoding='utf-8'))
    page.evaluate('X.profile=X.Save.defaults();X.profile.credits=20000;X.UI.shop()')
    button=page.locator('[data-act="upgrade:secondChance"]');assert '10000' in button.inner_text();button.click();assert button.is_disabled()
    assert page.evaluate('X.profile.upgrades.secondChance===1&&X.profile.credits===10000')
    page.evaluate('X.game.start(1);X.game.waveTimer=9999;X.game.player.x=600;X.game.player.y=600;X.game.player.invuln=0;X.game.hurtPlayer(999);X.game.pause()')
    assert page.evaluate('X.profile.upgrades.secondChance===0&&X.game.player.hp===100')
    page.evaluate('X.UI.hide();X.game.reviveFX.life=1.8;document.getElementById("toast").classList.remove("visible");X.UI.hudClock=-1;X.UI.hud(X.game)')
    page.wait_for_timeout(500);page.screenshot(path=str(ART/'second-chance-revival.png'))
    page.evaluate('X.game.state="play";X.game.creditReward(101);X.game.player.invuln=0;X.game.hurtPlayer(999);X.game.update(1/60)')
    assert page.evaluate('X.game.state==="dead"')
    assert page.evaluate('X.game.creditsAwarded===50&&X.profile.credits===10050')
    assert '50%' in page.locator('.panel').inner_text()
    page.get_by_role('button',name='АРСЕНАЛ',exact=True).click();button=page.locator('[data-act="upgrade:secondChance"]');assert button.is_enabled();button.click()
    assert page.evaluate('X.profile.upgrades.secondChance===1&&X.profile.credits===50')
    assert not errors and not network,(errors,network)
    browser.close()
    profile=ROOT/'.venv'/'edge-revival-profile'
    ctx=p.chromium.launch_persistent_context(str(profile),channel='msedge',headless=True,offline=True)
    pg=ctx.new_page();pg.on('pageerror',lambda e:errors.append(str(e)));pg.goto(url)
    pg.evaluate('X.profile=X.Save.defaults();X.profile.credits=20000;X.Economy.upgrade("secondChance");X.game.start(1);X.game.player.invuln=0;X.game.hurtPlayer(999);X.game.pause()');ctx.close()
    ctx=p.chromium.launch_persistent_context(str(profile),channel='msedge',headless=True,offline=True)
    pg=ctx.new_page();pg.on('pageerror',lambda e:errors.append(str(e)));pg.goto(url)
    assert pg.evaluate('X.profile.upgrades.secondChance===0&&X.profile.checkpoint.player.hp===100&&X.profile.checkpoint.reviveFX.life>0')
    pg.get_by_role('button',name='ПРОДОЛЖИТЬ · КОНТРОЛЬНАЯ ТОЧКА',exact=True).click()
    assert pg.evaluate('X.game.player.hp===100&&X.profile.upgrades.secondChance===0')
    pg.evaluate('X.game.pause();X.Slots.save(0);X.UI.settings()')
    with pg.expect_download() as download:pg.get_by_role('button',name='ЭКСПОРТ JSON',exact=True).click()
    export=ART/'revival-export.json';download.value.save_as(str(export))
    pg.evaluate('X.UI.action("doreset")');pg.locator('#import').set_input_files(str(export));pg.wait_for_timeout(100)
    assert pg.evaluate('X.profile.upgrades.secondChance===0&&X.Slots.entries[0].profile.upgrades.secondChance===0')
    pg.evaluate('X.Slots.restore(0);X.game.player.invuln=0;X.game.hurtPlayer(999);X.game.update(1/60)')
    assert pg.evaluate('X.game.state==="dead"&&X.profile.upgrades.secondChance===0')
    ctx.close();assert not errors and not network,(errors,network)
    report.update(uiPurchaseRebuy=True,fullEdgeRestartSpent=True,jsonAndSlotSpent=True,version='1.5.0',errors=errors,network=0)
    (ART/'revival-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False),flush=True)
